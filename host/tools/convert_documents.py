#!/usr/bin/env python3
"""Convert repository binary documents with MarkItDown and build an index."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path
import traceback

from markitdown import MarkItDown


BINARY_DOCUMENT_EXTENSIONS = {
    ".pdf", ".jpg", ".jpeg", ".png", ".gif", ".tif", ".tiff",
    ".doc", ".docx", ".ppt", ".pptx", ".xls", ".xlsx",
    ".zip", ".epro", ".epub", ".step", ".stp", ".wrl",
}
SKIP_PARTS = {".git", ".venv", "BUILD", "RELEASE", "third_party", "markitdown"}


def candidates(root: Path, only: Path | None = None):
    if only is not None:
        yield only
        return
    for path in sorted(root.rglob("*")):
        if not path.is_file() or any(part in SKIP_PARTS for part in path.parts):
            continue
        if path.suffix.lower() in BINARY_DOCUMENT_EXTENSIONS:
            yield path


def output_path(source: Path, root: Path, output: Path) -> Path:
    relative = source.relative_to(root)
    return output / relative.parent / f"{relative.name}.md"


def conversion_status(source: Path, content: str) -> str:
    """Describe the usefulness of the result, not just converter success."""
    if not content.strip():
        return "converted/no extractable text"
    if source.suffix.lower() in {".step", ".stp", ".wrl"}:
        return "converted/raw CAD text"
    if source.suffix.lower() in {".jpg", ".jpeg", ".png", ".gif", ".tif", ".tiff"}:
        return "converted/metadata only"
    return "converted/searchable text"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--only", type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)

    converter = MarkItDown(enable_plugins=False)
    rows = []
    only = args.only.resolve() if args.only else None
    if only is not None and (not only.is_file() or root not in only.parents):
        parser.error("--only must be a file below root")
    for source in candidates(root, only):
        destination = output_path(source, root, output)
        destination.parent.mkdir(parents=True, exist_ok=True)
        try:
            result = converter.convert_local(source)
            content = result.text_content or ""
            generated = f"<!-- Generated by Microsoft MarkItDown from {source.relative_to(root)} -->"
            if content.strip():
                generated += f"\n\n{content.rstrip()}"
            destination.write_text(
                generated + "\n",
                encoding="utf-8",
            )
            destination.with_suffix(destination.suffix + ".error.txt").unlink(missing_ok=True)
            status = conversion_status(source, content)
            rows.append((source.relative_to(root), destination.relative_to(output), status, len(content)))
            print(f"{status}: {source.relative_to(root)}", flush=True)
        except Exception as error:  # Keep a complete audit instead of stopping at one unsupported CAD file.
            failure = destination.with_suffix(destination.suffix + ".error.txt")
            failure.write_text(
                f"{type(error).__name__}: {error}\n\n{traceback.format_exc().rstrip()}\n",
                encoding="utf-8",
            )
            rows.append((source.relative_to(root), failure.relative_to(output), "unsupported/error", 0))
            destination.unlink(missing_ok=True)
            print(
                f"unsupported {source.relative_to(root)}: {type(error).__name__}: {error}",
                flush=True,
            )

    index = output / "INDEX.md"
    lines = [
        "# MarkItDown conversion index",
        "",
        f"Generated: {datetime.now(timezone.utc).isoformat()}",
        "",
        "| Source | Output | Status | Characters |",
        "| --- | --- | --- | ---: |",
    ]
    lines.extend(f"| `{src}` | `{dst}` | {status} | {size} |" for src, dst, status, size in rows)
    index.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {index} ({len(rows)} inputs)", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
